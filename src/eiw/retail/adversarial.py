"""Adversarial evaluation suite for the Retail BA Agent.

The development split is generated from public category templates. The holdout
split is loaded from a committed frozen JSONL file and is never generated by
this module. Both splits use the same explicit behavioral contract.
"""

from __future__ import annotations

