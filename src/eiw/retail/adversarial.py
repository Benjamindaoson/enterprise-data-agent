def build_development_cases() -> list[AdversarialCase]:
    """Build 168 public cases: 14 categories x 12 phrasings."""

    cases: list[AdversarialCase] = []
    for category, cores in _CATEGORY_CORES.items():
        for variant in range(2):
            for index, core in enumerate(cores, start=1):
                question = core if variant == 0 else f"Executive request: {core}"
                overrides: dict[str, Any] = {}
                if category == "wrong_time_range":
                    overrides = {
                        "current_weeks": [900 + index],
                        "previous_weeks": [800 + index],
                    }
                parent_question = None
                focus: dict[str, str] = {}
                if category == "multi_turn_followup":
                    parent_question = "Analyze recent sales by store and category."
                    focus = {"store": str((index - 1) % 3 + 1)}
                expected_metrics: list[str] = []
                expected_dimensions: list[str] = []
                expected_intents: list[str] = []
                if category == "paraphrase":
                    expected_metrics = ["sales_value"]
                    expected_dimensions = ["store", "commodity"]
                    expected_intents = ["diagnose"]
                cases.append(
                    AdversarialCase(
                        case_id=f"dev-{category}-{variant + 1}-{index:02d}",
                        split="development",
                        category=category,
                        question=question,
                        expected_status=_EXPECTED_STATUS[category],
                        expected_metrics=expected_metrics,
                        expected_dimensions=expected_dimensions,
                        expected_intents=expected_intents,
                        request_overrides=overrides,
                        parent_question=parent_question,
                        focus=focus,
                    )
                )
    return cases


def load_holdout_cases(path: Path = _FROZEN_HOLDOUT) -> list[AdversarialCase]:
    """Load the frozen 84-case holdout. This module never generates it."""

    rows = [
        AdversarialCase.model_validate_json(line)
        for line in path.read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]
    if len(rows) != 84:
        raise ValueError(f"frozen holdout must contain exactly 84 cases, found {len(rows)}")
    if any(case.split != "holdout" for case in rows):
        raise ValueError("frozen holdout contains a non-holdout case")
    counts = Counter(case.category for case in rows)
    if set(counts) != set(_CATEGORY_CORES) or any(count != 6 for count in counts.values()):
        raise ValueError("frozen holdout must contain six cases for each adversarial category")
    return rows


def all_adversarial_cases() -> list[AdversarialCase]:
    cases = [*build_development_cases(), *load_holdout_cases()]
    if len(cases) != 252:
        raise AssertionError(f"expected 252 adversarial questions, got {len(cases)}")
    return cases


class RetailAdversarialBenchmark:
    def __init__(self, runtime: RetailBARuntime) -> None:
        self.runtime = runtime

    def run(
        self,
        *,
        split: Literal["development", "holdout", "all"] = "all",
        max_cases: int | None = None,
    ) -> AdversarialBenchmarkResult:
        if split == "development":
            cases = build_development_cases()
        elif split == "holdout":
            cases = load_holdout_cases()
        else:
            cases = all_adversarial_cases()
        if max_cases is not None:
            cases = cases[:max_cases]

        results = [self._run_case(case) for case in cases]
        by_category_raw: dict[str, list[AdversarialCaseResult]] = defaultdict(list)
        for result in results:
            by_category_raw[result.category].append(result)
        by_category = {
            category: {
                "cases": len(items),
                "success_rate": round(
                    sum(item.success for item in items) / max(1, len(items)),
                    4,
                ),
                "semantic_coverage": round(
                    sum(item.semantic_coverage for item in items) / max(1, len(items)),
                    4,
                ),
            }
            for category, items in sorted(by_category_raw.items())
        }
        return AdversarialBenchmarkResult(
            cases=len(results),
            success_rate=round(
                sum(result.success for result in results) / max(1, len(results)),
                4,
            ),
            semantic_coverage=round(
                sum(result.semantic_coverage for result in results)
                / max(1, len(results)),
                4,
            ),
            by_category=by_category,
            results=results,
        )

    def _run_case(self, case: AdversarialCase) -> AdversarialCaseResult:
        if case.category == "malformed_model_response":
            return self._run_malformed_case(case)

        request_data: dict[str, Any] = {
            "question": case.question,
            **case.request_overrides,
        }
        if case.parent_question:
            parent = self.runtime.analyze(
                RetailAnalysisRequest(question=case.parent_question)
            )
            request_data.update(
                {
                    "parent_task_id": parent.task_id,
                    "current_weeks": list(parent.current_weeks),
                    "previous_weeks": list(parent.previous_weeks),
                    "focus": dict(case.focus),
                }
            )
        response = self.runtime.analyze(RetailAnalysisRequest.model_validate(request_data))
        status_match = response.status == case.expected_status
        semantic_coverage = self._semantic_coverage(case, response.semantics.model_dump())
        qualified = (
            case.category != "unsupported_causality"
            or (
                response.guardrail.get("action") == "QUALIFY"
                and bool(response.limitations)
            )
        )
        success = status_match and semantic_coverage == 1.0 and qualified
        return AdversarialCaseResult(
            case_id=case.case_id,
            split=case.split,
            category=case.category,
            success=success,
            status_match=status_match,
            semantic_coverage=semantic_coverage,
            observed_status=response.status,
            detail="" if qualified else "causal request was not explicitly qualified",
        )

    @staticmethod
    def _semantic_coverage(case: AdversarialCase, semantics: dict[str, Any]) -> float:
        expected = [
            *[(item, "metrics") for item in case.expected_metrics],
            *[(item, "dimensions") for item in case.expected_dimensions],
            *[(item, "intents") for item in case.expected_intents],
        ]
        if not expected:
            return 1.0
        matched = sum(
            item in set(semantics.get(field, []))
            for item, field in expected
        )
        return round(matched / len(expected), 4)

    @staticmethod
    def _run_malformed_case(case: AdversarialCase) -> AdversarialCaseResult:
        rejected = 0
        for parser in (
            OpenAICompatibleSupervisor._parse_json,
            OpenAICompatibleSpecialistPolicy._parse_json,
        ):
            try:
                parser(case.question)
            except (ValueError, json.JSONDecodeError):
                rejected += 1
        success = rejected == 2
        return AdversarialCaseResult(
            case_id=case.case_id,
            split=case.split,
            category=case.category,
            success=success,
            status_match=success,
            semantic_coverage=1.0,
            observed_status="REJECTED_CONTRACT" if success else "ACCEPTED_INVALID",
        )
