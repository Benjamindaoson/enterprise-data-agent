_REPO_ROOT = Path(__file__).resolve().parents[3]
_FROZEN_HOLDOUT = _REPO_ROOT / "evaluation/retail/adversarial_holdout_v1.jsonl"


class AdversarialCase(BaseModel):
    case_id: str
    split: Literal["development", "holdout"]
    category: str
    question: str
    expected_status: str
    expected_metrics: list[str] = Field(default_factory=list)
    expected_dimensions: list[str] = Field(default_factory=list)
    expected_intents: list[str] = Field(default_factory=list)
    request_overrides: dict[str, Any] = Field(default_factory=dict)
    parent_question: str | None = None
    focus: dict[str, str] = Field(default_factory=dict)


class AdversarialCaseResult(BaseModel):
    case_id: str
    split: str
    category: str
    success: bool
    status_match: bool
    semantic_coverage: float
    observed_status: str
    detail: str = ""


class AdversarialBenchmarkResult(BaseModel):
    suite: str = "RetailAdversarialBench-v1"
    cases: int
    success_rate: float
    semantic_coverage: float
    by_category: dict[str, dict[str, float | int]]
    results: list[AdversarialCaseResult]


